// L1: create and fund testnet accounts via the faucet (one issuer, one venue, four members).
// Seeds go to ledger/.env (gitignored); addresses go to ledger/accounts.json (committed).
import { existsSync, writeFileSync } from 'node:fs'
import { Client } from 'xrpl'
import { MEMBER_IDS, TESTNET, paths, seedEnvKey } from '../src/config.ts'

if (existsSync(paths.env) && !process.argv.includes('--force')) {
  console.error(`${paths.env} already exists; refusing to overwrite keys. Re-run with --force to replace them.`)
  process.exit(1)
}

const roles = ['issuer', 'venue', ...MEMBER_IDS]
const client = new Client(TESTNET.wsUrl)
await client.connect()

const wallets: Record<string, { address: string; seed: string }> = {}
try {
  // Sequential: the faucet rate-limits bursts, and this only runs once.
  for (const role of roles) {
    const { wallet, balance } = await client.fundWallet()
    wallets[role] = { address: wallet.address, seed: wallet.seed! }
    console.log(`funded ${role.padEnd(9)} ${wallet.address} ${balance} XRP`)
  }
} finally {
  await client.disconnect()
}

const env = [
  '# Generated by scripts/setup-accounts.ts. XRPL testnet keys: never commit.',
  `XRPL_WS_URL=${TESTNET.wsUrl}`,
  ...roles.map((role) => `${seedEnvKey(role)}=${wallets[role].seed}`),
  '',
].join('\n')
writeFileSync(paths.env, env, { mode: 0o600 })

const accounts = {
  network: 'testnet',
  issuer: wallets.issuer.address,
  venue: wallets.venue.address,
  members: Object.fromEntries(MEMBER_IDS.map((id) => [id, wallets[id].address])),
}
writeFileSync(paths.accounts, JSON.stringify(accounts, null, 2) + '\n')

console.log(`wrote ${paths.env} and ${paths.accounts}`)
