// L1: create and fund testnet accounts via the faucet: one issuer, one venue, and every MEMBER_IDS entry.
// Only roles without a seed in ledger/.env are created, so adding a member leaves existing keys alone:
// new seeds are appended to .env (gitignored) and all addresses are written to accounts.json (committed).
// --force replaces every account and rewrites .env.
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { Client, Wallet } from 'xrpl'
import { MEMBER_IDS, TESTNET, paths, seedEnvKey } from '../src/config.ts'
import { type Accounts, loadAccounts, loadEnv } from '../src/keys.ts'

const force = process.argv.includes('--force')
const roles = ['issuer', 'venue', ...MEMBER_IDS]
const env = force ? {} : loadEnv()
const recorded: Partial<Accounts> = !force && existsSync(paths.accounts) ? loadAccounts() : {}
const recordedAddress = (role: string) =>
  role === 'issuer' || role === 'venue' ? recorded[role] : recorded.members?.[role]

const wallets: Record<string, Wallet> = {}
const missing: string[] = []
for (const role of roles) {
  const seed = env[seedEnvKey(role)]
  const address = recordedAddress(role)
  if (seed) {
    wallets[role] = Wallet.fromSeed(seed)
    if (address && address !== wallets[role].address) {
      console.error(`${seedEnvKey(role)} is for ${wallets[role].address}, but accounts.json says ${role} is ${address}.`)
      process.exit(1)
    }
  } else if (address) {
    console.error(`accounts.json has ${role} (${address}) but .env has no ${seedEnvKey(role)}. Restore it, or re-run with --force.`)
    process.exit(1)
  } else {
    missing.push(role)
  }
}

if (missing.length === 0) {
  console.log('every account already exists; nothing to do')
  process.exit(0)
}

const client = new Client(TESTNET.wsUrl)
await client.connect()
try {
  // Sequential: the faucet rate-limits bursts.
  for (const role of missing) {
    const { wallet, balance } = await client.fundWallet()
    wallets[role] = wallet
    console.log(`funded ${role.padEnd(9)} ${wallet.address} ${balance} XRP`)
  }
} finally {
  await client.disconnect()
}

if (force || !existsSync(paths.env)) {
  const lines = [
    '# Generated by scripts/setup-accounts.ts. XRPL testnet keys: never commit.',
    `XRPL_WS_URL=${TESTNET.wsUrl}`,
    ...roles.map((role) => `${seedEnvKey(role)}=${wallets[role].seed}`),
  ]
  writeFileSync(paths.env, lines.join('\n') + '\n', { mode: 0o600 })
} else {
  // Append only, so existing keys are never rewritten.
  const separator = readFileSync(paths.env, 'utf8').endsWith('\n') ? '' : '\n'
  appendFileSync(paths.env, separator + missing.map((role) => `${seedEnvKey(role)}=${wallets[role].seed}\n`).join(''))
}

const accounts: Accounts = {
  network: 'testnet',
  issuer: wallets.issuer.address,
  venue: wallets.venue.address,
  members: Object.fromEntries(MEMBER_IDS.map((id) => [id, wallets[id].address])),
}
writeFileSync(paths.accounts, JSON.stringify(accounts, null, 2) + '\n')
console.log(`added ${missing.join(', ')}; wrote ${paths.env} and ${paths.accounts}`)
